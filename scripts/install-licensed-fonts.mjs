// Copies the plan's licensed fonts into the ignored public/fonts/licensed/ folder for LOCAL preview.
// SFT Schrifted Sans (trial) and Zenitha Classic (personal use only) must never be committed or
// deployed until the team buys licenses; .gitignore excludes the destination folder.
//
// Usage: npm run fonts:licensed [-- --from <folder>]
// The source folder must contain sft_schrifted_sans/ and zenitha_classic/ as supplied to the team.
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const destination = path.join(root, 'public', 'fonts', 'licensed');

const fonts = [
  {
    source: path.join('sft_schrifted_sans', 'SFT Schrifted Sans TRIAL Var.ttf'),
    target: 'sft-schrifted-sans-var.ttf',
    face: `@font-face {
  font-family: 'SFT Schrifted Sans';
  src: url('/fonts/licensed/sft-schrifted-sans-var.ttf') format('truetype');
  font-weight: 200 900;
  font-style: normal;
  font-display: swap;
}`,
  },
  {
    source: path.join('zenitha_classic', 'ZenithaClassic_PERSONAL_USE_ONLY.otf'),
    target: 'zenitha-classic.otf',
    face: `@font-face {
  font-family: 'Zenitha Classic';
  src: url('/fonts/licensed/zenitha-classic.otf') format('opentype');
  font-weight: 400;
  font-style: normal;
  font-display: swap;
}`,
  },
];

function argumentValue(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

const candidates = [
  argumentValue('--from'),
  process.env.LICENSED_FONTS_DIR,
  root,
  // The team keeps the supplied font folders beside the build package on this machine.
  path.resolve(root, '..', '..', 'Zentracodes'),
].filter(Boolean);

const sourceRoot = candidates.find((candidate) =>
  fonts.every((font) => existsSync(path.join(candidate, font.source))),
);

if (!sourceRoot) {
  console.log(
    'Licensed fonts not found, so the free fallbacks (Archivo, Cinzel Decorative) stay in use.\n' +
      'Pass --from <folder containing sft_schrifted_sans/ and zenitha_classic/> to install them.',
  );
  process.exit(0);
}

mkdirSync(destination, { recursive: true });
for (const font of fonts) {
  copyFileSync(path.join(sourceRoot, font.source), path.join(destination, font.target));
}
writeFileSync(
  path.join(destination, 'fonts.css'),
  `/* Local preview only: trial and personal-use fonts. Generated by scripts/install-licensed-fonts.mjs; not in Git. */\n${fonts
    .map((font) => font.face)
    .join('\n\n')}\n`,
);
console.log(
  `Installed SFT Schrifted Sans and Zenitha Classic for local preview (${path.relative(root, destination)}). Restart the dev server to use them.`,
);
