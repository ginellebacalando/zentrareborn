/**
 * Writes config/photo-placeholders.ts: a tiny blurred copy of every event page photo
 * (config/event-photos.ts), shown while the photo loads (next/image placeholder="blur").
 * Run after changing the photos: npm run photos:placeholders
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { eventPhotos } from '../config/event-photos';

const sources = [
  ...new Set(
    Object.values(eventPhotos).flatMap((set) => [
      ...(set.hero ? [set.hero.src] : []),
      ...set.gallery.map((photo) => photo.src),
    ]),
  ),
].sort();

async function main() {
  const entries: string[] = [];
  for (const src of sources) {
    const file = path.join(process.cwd(), 'public', ...src.split('/').filter(Boolean));
    const data = await sharp(file)
      .resize(16, 16, { fit: 'inside' })
      .webp({ quality: 40 })
      .toBuffer();
    entries.push(`  '${src}': 'data:image/webp;base64,${data.toString('base64')}',`);
  }

  writeFileSync(
    path.join(process.cwd(), 'config', 'photo-placeholders.ts'),
    [
      '// Generated by scripts/build-photo-placeholders.ts (npm run photos:placeholders); do not edit.',
      '/** A 16px blurred copy of each event page photo, shown while the photo loads. */',
      'export const PHOTO_PLACEHOLDERS: Readonly<Record<string, string>> = {',
      ...entries,
      '};',
      '',
    ].join('\n'),
  );
  console.log(`Wrote ${entries.length} placeholders to config/photo-placeholders.ts.`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
